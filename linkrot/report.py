"""Report builders: Markdown (human) and JSON (machine)."""

from __future__ import annotations

import json
from datetime import datetime, timezone


def _escape_cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def build_markdown(dead: list[dict], total_files: int, total_links: int,
                   elapsed: float) -> str:
    """Build the Markdown report from a list of dead-link dicts."""
    lines = [
        "# Linkrot report",
        "",
        f"Scanned {total_files} Markdown file(s), {total_links} unique link(s) "
        f"in {elapsed:.1f}s.",
        f"**Dead links: {len(dead)}**",
        "",
    ]
    if not dead:
        lines.append("No dead links found. 🎉")
        lines.append("")
        return "\n".join(lines)

    # Group by file.
    by_file: dict[str, list[dict]] = {}
    for entry in dead:
        by_file.setdefault(entry["file"], []).append(entry)

    for filename in sorted(by_file):
        lines.append(f"## {filename}")
        lines.append("")
        lines.append("| Line | Link | Status | Detail |")
        lines.append("| --- | --- | --- | --- |")
        for entry in by_file[filename]:
            status = entry["status"] if entry["status"] is not None else "—"
            lines.append(
                f"| {entry['line']} "
                f"| [{_escape_cell(entry['text'] or entry['url'])}]({entry['url']}) "
                f"| {status} "
                f"| {_escape_cell(entry['detail'])} |"
            )
        lines.append("")

    lines.append(f"_Generated by linkrot at "
                f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}_")
    lines.append("")
    return "\n".join(lines)


def build_json(dead: list[dict], total_files: int, total_links: int,
               elapsed: float) -> str:
    """Build the JSON report from a list of dead-link dicts."""
    payload = {
        "tool": "linkrot",
        "dead_links": len(dead),
        "files_scanned": total_files,
        "links_checked": total_links,
        "elapsed_seconds": round(elapsed, 2),
        "dead": dead,
    }
    return json.dumps(payload, indent=2) + "\n"
